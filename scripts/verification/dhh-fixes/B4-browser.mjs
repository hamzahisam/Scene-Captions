import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
const playwrightPath=process.env.PLAYWRIGHT_MODULE||'/Users/zuhairmerchant/TexPilot/yarn-erp/node_modules/playwright/index.mjs';
const {chromium}=await import(playwrightPath);
const baseURL=process.env.BASE_URL||'http://127.0.0.1:3000';
const output=process.env.B4_OUTPUT||'artifacts/dhh-fixes/B4-browser.json';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const status=page.locator('p[role="status"]');
const registry=async()=>page.evaluate(()=>JSON.parse(localStorage.getItem('scenecaptions.study-registry.v1')||'null'));
const sessionFor=async participantId=>Object.values((await registry()).sessions).find(session=>session.participantId===participantId);
const create=async participantId=>{await page.getByLabel('Participant code',{exact:true}).fill(participantId);await page.getByLabel('Researcher code',{exact:true}).fill('012345');await page.getByRole('button',{name:'Create session',exact:true}).click()};
try{
 await page.goto(`${baseURL}/session`);
 await page.evaluate(()=>localStorage.clear());
 await page.reload();
 await page.getByLabel('Design',{exact:true}).selectOption('within-pilot');
 await page.getByLabel('Hair Love',{exact:true}).check();
 await page.getByLabel('I am preparing a local technical rehearsal; study consent is handled separately.',{exact:true}).check();
 await create('P-001');
 await status.filter({hasText:'Saved pilot slot: pilot-2-0.'}).waitFor();
 const first=await sessionFor('P-001');
 assert.equal(first?.allocationSlot,'pilot-2-0');
 assert.deepEqual(first?.sequence.map(x=>x.filmId),['soar','hair-love']);
 await page.getByText('Next unused two-condition pilot slot: 1.').waitFor();
 await create('P-002');
 await status.filter({hasText:'Saved pilot slot: pilot-2-1.'}).waitFor();
 assert.equal((await sessionFor('P-002'))?.allocationSlot,'pilot-2-1');
 await page.getByLabel('Override the next unused slot',{exact:true}).check();
 await page.getByLabel('Override slot number',{exact:true}).fill('0');
 await create('P-003');
 await status.filter({hasText:'Record a reason before overriding the next unused pilot slot.'}).waitFor();
 assert.equal(await sessionFor('P-003'),undefined);
 await page.getByLabel('Reason for override (required)',{exact:true}).fill('Room schedule requires the first sequence again.');
 await page.getByRole('button',{name:'Create session',exact:true}).click();
 await status.filter({hasText:'Saved pilot slot: pilot-2-0.'}).waitFor();
 const overridden=await sessionFor('P-003');
 assert.equal(overridden?.allocationSlot,'pilot-2-0');
 assert.equal(overridden?.slotOverride?.reason,'Room schedule requires the first sequence again.');
 assert.match(await status.textContent(),/Override reason recorded\./);
 await page.getByLabel('Three fixed detail conditions (Essential, Balanced, Rich)',{exact:true}).check();
 await page.getByLabel('Big Buck Bunny',{exact:true}).check();
 await page.getByText('Next unused three-condition pilot slot: 0.').waitFor();
 await create('P-004');
 await status.filter({hasText:'Saved pilot slot: pilot-3-0.'}).waitFor();
 const three=await sessionFor('P-004');
 assert.equal(three?.allocationSlot,'pilot-3-0');
 assert.deepEqual(three?.sequence.map(x=>x.condition),['essential','balanced','rich']);
 assert.equal(new Set(three?.sequence.map(x=>x.filmId)).size,3);
 await page.getByLabel('Design',{exact:true}).selectOption('between');
 await page.getByRole('button',{name:'Generate allocation list',exact:true}).click();
 await status.filter({hasText:'Allocation list saved.'}).waitFor();
 await create('P-005');
 await status.filter({hasText:'Saved fixed allocation: frequent-1.'}).waitFor();
 const between0=await sessionFor('P-005');
 assert.deepEqual(between0?.sequence.map(x=>x.filmId),['big-buck-bunny','soar','hair-love']);
 await create('P-006');
 await status.filter({hasText:'Saved fixed allocation: frequent-2.'}).waitFor();
 const between1=await sessionFor('P-006');
 assert.deepEqual(between1?.sequence.map(x=>x.filmId),['soar','hair-love','big-buck-bunny']);
 assert.ok(between1?.sequence.every(x=>x.condition===between1.sequence[0].condition));
 await page.reload();
 const saved=await registry();
 assert.equal(Object.values(saved.sessions).length,6);
 assert.deepEqual(Object.values(saved.sessions).find(s=>s.participantId==='P-006')?.sequence.map(x=>x.filmId),['soar','hair-love','big-buck-bunny']);
 await page.getByLabel('Design',{exact:true}).selectOption('within-pilot');
 await page.getByText('Next unused two-condition pilot slot: 2.').waitFor();
 await page.getByLabel('Three fixed detail conditions (Essential, Balanced, Rich)',{exact:true}).check();
 await page.getByText('Next unused three-condition pilot slot: 1.').waitFor();
 assert.deepEqual(errors,[]);
 const evidence={passed:true,sessions:Object.values(saved.sessions).map(s=>({participantId:s.participantId,allocationSlot:s.allocationSlot,reason:s.slotOverride?.reason,films:s.sequence.map(x=>x.filmId),conditions:s.sequence.map(x=>x.condition)})),errors};
 mkdirSync('artifacts/dhh-fixes',{recursive:true});
 writeFileSync(output,JSON.stringify(evidence,null,2));
 console.log('B4 setup browser checks passed: auto slots, grouped schemes, reasoned override, between rotation, reload stability');
} finally {await browser.close()}
